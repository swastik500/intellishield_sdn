"""
================================================================================
IntelliShield SDN — Phase 6: HDBSCAN Clustering + ADWIN Drift Detection
================================================================================

File        : advanced_analytics/hdbscan_clusterer.py
Author      : IntelliShield SDN Research Team
Version     : 1.0.0
Phase       : Phase 6 — Advanced Analytics

Description:
    Periodic HDBSCAN density-based clustering of the 15-dimensional
    feature vectors generated by Phase 4's FeatureBuilder.

    HDBSCAN (Hierarchical Density-Based Spatial Clustering with Noise):
        Unlike k-Means, HDBSCAN does NOT require pre-specifying `k`.
        It discovers clusters of arbitrary shape based on data density.
        Points in sparse regions are labelled -1 (NOISE / OUTLIER).

        Key advantage for DDoS detection:
            Normal traffic forms one dense cluster.
            Different attack types (SYN flood, UDP flood, ICMP) form
            separate clusters. New attack types appear as noise points
            that eventually form new clusters → zero-day detection.

    Clustering is a BATCH operation:
        Unlike ADWIN (online, per-sample), HDBSCAN runs periodically
        on a buffer of recent feature vectors. Triggered every
        CLUSTER_CYCLE_COUNT monitoring cycles (default: 10 cycles = 50s).

    Cluster labelling heuristic:
        After clustering, each cluster is classified using its centroid:
          NORMAL      → high entropy_score (≥ 0.6) AND low packet_rate (≤ 500)
          ATTACK      → low entropy_score (< 0.3) OR high packet_rate (> 5000)
          SUSPICIOUS  → in between
          NOISE       → HDBSCAN label -1 (sparse/outlier)

    Outputs:
        Console output: cluster summary table
        logs/cluster_labels.csv: per-vector cluster assignment
        logs/cluster_summary.json: session-level cluster statistics

IEEE Relevance:
    HDBSCAN provides unsupervised traffic profiling without labelled data.
    This is cited as a key SDN security research contribution — the system
    learns what "attack traffic looks like" without being told explicitly.

================================================================================
"""

import os
import csv
import json
import logging
import traceback
from datetime import datetime
from typing import List, Dict, Optional, Tuple
from collections import defaultdict

import numpy as np
from sklearn.cluster import HDBSCAN
from sklearn.preprocessing import StandardScaler

logger = logging.getLogger("intellishield.hdbscan")

_BASE_DIR            = os.path.dirname(os.path.abspath(__file__))
_LOGS_DIR            = os.path.join(_BASE_DIR, "..", "logs")
CLUSTER_CSV_PATH     = os.path.join(_LOGS_DIR, "cluster_labels.csv")
CLUSTER_SUMMARY_PATH = os.path.join(_LOGS_DIR, "cluster_summary.json")

CLUSTER_CSV_HEADERS = [
    "timestamp", "switch_id", "cluster_id", "cluster_label",
    "packet_rate_mean", "entropy_score", "flow_count", "confidence",
]

# How many monitoring cycles between HDBSCAN runs (10 cycles × 5s = 50s)
CLUSTER_CYCLE_COUNT = 10

# Feature indices for cluster labelling heuristic
# (these match FEATURE_NAMES order from feature_builder.py)
IDX_PKT_RATE_MEAN = 0    # packet_rate_mean
IDX_BYTE_RATE_MEAN = 2   # byte_rate_mean
IDX_FLOW_COUNT    = 4    # flow_count
IDX_ENTROPY_SCORE = 13   # entropy_score

# Cluster label thresholds
NORMAL_ENTROPY_MIN  = 0.6
ATTACK_ENTROPY_MAX  = 0.3
ATTACK_PKT_RATE_MIN = 5000.0


class HDBSCANClusterer:
    """
    Periodic HDBSCAN density-based clusterer for IntelliShield SDN.

    Usage (from flow_monitor.py):
        clusterer = HDBSCANClusterer(switch_id=1)

        # On each monitoring cycle:
        clusterer.add_vector(vec, feature_names)  # buffer the vector

        # Auto-triggers clustering every CLUSTER_CYCLE_COUNT calls
        # OR call manually:
        clusterer.run_clustering()
    """

    def __init__(self,
                 switch_id       : int   = 0,
                 min_cluster_size: int   = 5,
                 min_samples     : int   = 3,
                 cycle_count     : int   = CLUSTER_CYCLE_COUNT):
        """
        Args:
            switch_id       : Switch DPID for this clusterer instance.
            min_cluster_size: HDBSCAN — min points to form a cluster.
            min_samples     : HDBSCAN — min samples in neighbourhood.
            cycle_count     : Cluster every N update() calls.
        """
        self.switch_id        = switch_id
        self.min_cluster_size = min_cluster_size
        self.min_samples      = min_samples
        self.cycle_count      = cycle_count

        self._buffer       : List[List[float]] = []   # feature vectors
        self._timestamps   : List[str]          = []
        self._cycle_counter: int = 0
        self._run_count    : int = 0              # total HDBSCAN runs

        self._last_cluster_summary: dict = {}
        self._scaler = StandardScaler()

        self._init_logs()
        logger.info("[HDBSCAN] Initialised for switch %d.  "
                    "min_cluster_size=%d  trigger_every=%d cycles",
                    switch_id, min_cluster_size, cycle_count)

    # ─── Public API ───────────────────────────────────────────────────────────

    def add_vector(self, vector: List[float],
                   feature_names: List[str]) -> Optional[dict]:
        """
        Buffer one feature vector for future clustering.

        Automatically triggers HDBSCAN when buffer reaches cycle_count.

        Args:
            vector       : 15-dim feature vector from FeatureBuilder.build().
            feature_names: FEATURE_NAMES list for column reference.

        Returns:
            Cluster summary dict if clustering ran this call, else None.
        """
        self._buffer.append(list(vector))
        self._timestamps.append(datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
        self._cycle_counter += 1

        if self._cycle_counter >= self.cycle_count:
            self._cycle_counter = 0
            return self.run_clustering(feature_names)

        return None

    def run_clustering(self,
                        feature_names: Optional[List[str]] = None) -> Optional[dict]:
        """
        Run HDBSCAN on the current buffer. Called automatically by add_vector()
        or can be called manually.

        Returns:
            Cluster summary dict, or None if buffer too small.
        """
        if len(self._buffer) < self.min_cluster_size * 2:
            logger.debug("[HDBSCAN] Buffer too small (%d). Need ≥ %d.",
                         len(self._buffer), self.min_cluster_size * 2)
            return None

        try:
            data = np.array(self._buffer, dtype=float)

            # Standardise before clustering
            data_scaled = self._scaler.fit_transform(data)

            # Run HDBSCAN
            model = HDBSCAN(
                min_cluster_size = self.min_cluster_size,
                min_samples      = self.min_samples,
                metric           = "euclidean",
            )
            labels = model.fit_predict(data_scaled)

            self._run_count += 1

            # Analyse clusters
            summary = self._analyse_clusters(data, labels, feature_names)
            self._last_cluster_summary = summary

            # Log to CSV and console
            self._log_cluster_assignments(data, labels, self._timestamps)
            self._update_summary_json(summary)
            self._print_cluster_summary(summary)

            # Keep only the last cycle_count vectors (rolling buffer)
            keep = self.cycle_count
            self._buffer     = self._buffer[-keep:]
            self._timestamps = self._timestamps[-keep:]

            return summary

        except Exception:
            logger.error("[HDBSCAN] Clustering failed:\n%s",
                         traceback.format_exc())
            return None

    # ─── Cluster Analysis ─────────────────────────────────────────────────────

    def _analyse_clusters(self,
                           data    : np.ndarray,
                           labels  : np.ndarray,
                           feature_names: Optional[List[str]]) -> dict:
        """
        For each cluster found by HDBSCAN, compute centroid statistics
        and assign a traffic label (NORMAL / ATTACK / SUSPICIOUS / NOISE).

        Returns:
            dict with clusters list and summary counts.
        """
        unique_labels = sorted(set(labels))
        clusters = []

        for cid in unique_labels:
            mask      = labels == cid
            members   = data[mask]
            n_members = int(np.sum(mask))

            if cid == -1:
                # Noise points
                cluster_label = "NOISE"
                confidence    = 0.0
                centroid      = members.mean(axis=0) if len(members) > 0 else np.zeros(data.shape[1])
            else:
                centroid      = members.mean(axis=0)
                cluster_label, confidence = self._label_cluster(centroid)

            clusters.append({
                "cluster_id"       : int(cid),
                "cluster_label"    : cluster_label,
                "size"             : n_members,
                "confidence"       : round(confidence, 3),
                "centroid_pkt_rate": round(float(centroid[IDX_PKT_RATE_MEAN]), 2),
                "centroid_entropy" : round(float(centroid[IDX_ENTROPY_SCORE]), 4),
                "centroid_flows"   : round(float(centroid[IDX_FLOW_COUNT]),    2),
            })

        # Summary counts
        n_normal     = sum(1 for c in clusters if c["cluster_label"] == "NORMAL")
        n_attack     = sum(1 for c in clusters if c["cluster_label"] == "ATTACK")
        n_suspicious = sum(1 for c in clusters if c["cluster_label"] == "SUSPICIOUS")
        n_noise      = sum(1 for c in clusters if c["cluster_label"] == "NOISE")

        return {
            "timestamp"   : datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
            "switch_id"   : self.switch_id,
            "run_count"   : self._run_count,
            "total_points": len(data),
            "n_clusters"  : len([c for c in clusters if c["cluster_id"] != -1]),
            "n_normal"    : n_normal,
            "n_attack"    : n_attack,
            "n_suspicious": n_suspicious,
            "n_noise"      : n_noise,
            "clusters"    : clusters,
        }

    def _label_cluster(self, centroid: np.ndarray) -> Tuple[str, float]:
        """
        Apply heuristic rules to classify a cluster centroid.

        Rules:
            ATTACK      → entropy_score < 0.3  OR  packet_rate > 5000
            NORMAL      → entropy_score ≥ 0.6  AND packet_rate ≤ 500
            SUSPICIOUS  → everything else

        Returns:
            (label_str, confidence_0_to_1)
        """
        entropy  = float(centroid[IDX_ENTROPY_SCORE])
        pkt_rate = float(centroid[IDX_PKT_RATE_MEAN])

        if entropy < ATTACK_ENTROPY_MAX or pkt_rate > ATTACK_PKT_RATE_MIN:
            # Strong attack indicators
            conf = min(1.0, (1 - entropy / ATTACK_ENTROPY_MAX) * 0.5 +
                       min(pkt_rate / ATTACK_PKT_RATE_MIN, 1.0) * 0.5)
            return "ATTACK", conf

        if entropy >= NORMAL_ENTROPY_MIN and pkt_rate <= 500:
            conf = min(1.0, entropy)
            return "NORMAL", conf

        return "SUSPICIOUS", 0.5

    # ─── Logging ──────────────────────────────────────────────────────────────

    def _init_logs(self) -> None:
        os.makedirs(_LOGS_DIR, exist_ok=True)
        if not os.path.exists(CLUSTER_CSV_PATH):
            with open(CLUSTER_CSV_PATH, "w", newline="") as f:
                csv.writer(f).writerow(CLUSTER_CSV_HEADERS)
        if not os.path.exists(CLUSTER_SUMMARY_PATH):
            with open(CLUSTER_SUMMARY_PATH, "w") as f:
                json.dump({"description": "IntelliShield Phase 6 — HDBSCAN Cluster History",
                           "runs": []}, f, indent=2)

    def _log_cluster_assignments(self,
                                  data      : np.ndarray,
                                  labels    : np.ndarray,
                                  timestamps: List[str]) -> None:
        with open(CLUSTER_CSV_PATH, "a", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=CLUSTER_CSV_HEADERS)
            for i, (vec, lbl, ts) in enumerate(zip(data, labels, timestamps)):
                label_str, conf = self._label_cluster(vec) if lbl != -1 else ("NOISE", 0.0)
                writer.writerow({
                    "timestamp"       : ts,
                    "switch_id"       : self.switch_id,
                    "cluster_id"      : int(lbl),
                    "cluster_label"   : label_str,
                    "packet_rate_mean": round(float(vec[IDX_PKT_RATE_MEAN]), 2),
                    "entropy_score"   : round(float(vec[IDX_ENTROPY_SCORE]), 4),
                    "flow_count"      : round(float(vec[IDX_FLOW_COUNT]),    1),
                    "confidence"      : conf,
                })

    def _update_summary_json(self, summary: dict) -> None:
        try:
            with open(CLUSTER_SUMMARY_PATH, "r") as f:
                data = json.load(f)
            data.setdefault("runs", []).append(summary)
            with open(CLUSTER_SUMMARY_PATH, "w") as f:
                json.dump(data, f, indent=2)
        except Exception:
            logger.error("[HDBSCAN] Summary update failed:\n%s", traceback.format_exc())

    def _print_cluster_summary(self, summary: dict) -> None:
        border = "=" * 60
        print(f"\n{border}")
        print(f"  [HDBSCAN] Clustering Run #{summary['run_count']}  "
              f"|  Switch {summary['switch_id']}")
        print(f"  {summary['total_points']} vectors  →  "
              f"{summary['n_clusters']} clusters found")
        print(f"  Normal: {summary['n_normal']}  Attack: {summary['n_attack']}  "
              f"Suspicious: {summary['n_suspicious']}  Noise: {summary['n_noise']}")
        print(f"{'─' * 60}")
        print(f"  {'Cluster':<10}{'Label':<14}{'Size':<8}"
              f"{'Pkt/s':<12}{'Entropy':<10}{'Conf':<8}")
        print(f"{'─' * 60}")
        for c in summary["clusters"]:
            icon = {"NORMAL": "✅", "ATTACK": "🚨",
                    "SUSPICIOUS": "⚠️ ", "NOISE": "⬜"}.get(c["cluster_label"], "?")
            cid_str = str(c["cluster_id"]) if c["cluster_id"] != -1 else "NOISE"
            print(f"  {cid_str:<10}{icon} {c['cluster_label']:<12}"
                  f"{c['size']:<8}{c['centroid_pkt_rate']:<12.1f}"
                  f"{c['centroid_entropy']:<10.4f}{c['confidence']:<8.3f}")
        print(f"{border}\n")


# ─── Multi-Switch Cluster Manager ─────────────────────────────────────────────

class ClusterManager:
    """
    Manages one HDBSCANClusterer per switch.

    Usage (from flow_monitor.py):
        cluster_mgr = ClusterManager()

        # On each ML detection cycle:
        cluster_mgr.add_vector(
            switch_id     = dpid,
            vector        = vec,
            feature_names = FEATURE_NAMES,
        )
    """

    def __init__(self,
                 min_cluster_size: int = 5,
                 cycle_count     : int = CLUSTER_CYCLE_COUNT):
        self.min_cluster_size = min_cluster_size
        self.cycle_count      = cycle_count
        self._clusterers: Dict[int, HDBSCANClusterer] = {}
        logger.info("[ClusterManager] Initialised.")

    def add_vector(self,
                   switch_id    : int,
                   vector       : List[float],
                   feature_names: List[str]) -> Optional[dict]:
        """
        Buffer a feature vector for the given switch.
        Triggers HDBSCAN automatically every cycle_count calls.
        """
        if switch_id not in self._clusterers:
            self._clusterers[switch_id] = HDBSCANClusterer(
                switch_id        = switch_id,
                min_cluster_size = self.min_cluster_size,
                cycle_count      = self.cycle_count,
            )
        return self._clusterers[switch_id].add_vector(vector, feature_names)

    def get_last_summary(self, switch_id: int) -> Optional[dict]:
        if switch_id in self._clusterers:
            return self._clusterers[switch_id]._last_cluster_summary
        return None


