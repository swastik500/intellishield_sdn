if __name__ == "__main__":
    import random
    logging.basicConfig(level=logging.INFO,
                        format="%(asctime)s  %(levelname)-8s %(name)s — %(message)s")

    print("=" * 60)
    print("  HDBSCAN Self-Test — Synthetic normal + attack data")
    print("=" * 60)

    N_FEATURES = 15
    # Feature indices: 0=pkt_rate_mean, 13=entropy_score

    def make_normal(n):
        rows = []
        for _ in range(n):
            row = [random.uniform(0, 1)] * N_FEATURES
            row[0]  = random.gauss(200, 50)    # pkt_rate_mean
            row[13] = random.uniform(0.7, 1.0) # entropy_score
            rows.append(row)
        return rows

    def make_attack(n):
        rows = []
        for _ in range(n):
            row = [random.uniform(0, 1)] * N_FEATURES
            row[0]  = random.gauss(90000, 5000) # pkt_rate_mean (flood)
            row[13] = random.uniform(0.0, 0.1)  # entropy collapse
            rows.append(row)
        return rows

    clusterer = HDBSCANClusterer(switch_id=1, min_cluster_size=5, cycle_count=100)

    feature_names = [f"f{i}" for i in range(N_FEATURES)]
    feature_names[0]  = "packet_rate_mean"
    feature_names[13] = "entropy_score"
    feature_names[4]  = "flow_count"

    # Buffer normal + attack vectors
    for vec in make_normal(30) + make_attack(20):
        clusterer.add_vector(vec, feature_names)

    # Force clustering
    summary = clusterer.run_clustering(feature_names)

    if summary:
        print(f"\n  ✅ Found {summary['n_clusters']} cluster(s)")
        print(f"     ATTACK clusters : {summary['n_attack']}")
        print(f"     NORMAL clusters : {summary['n_normal']}")
    else:
        print("  ⚠️  No clusters found (buffer too small or all noise)")

    print("\n  HDBSCAN Self-Test PASSED")
    print("=" * 60)
